export function getLocaleDirection(locale: Locale): TextDirection {
  return LOCALE_OPTIONS.find((opt) => opt.code === locale)?.dir ?? 'ltr';
}

export function getInitialLocale(): Locale {
  try {
    const saved = localStorage.getItem('remueble_locale');
    const validCodes = LOCALE_OPTIONS.map((o) => o.code);
    if (saved && validCodes.includes(saved as Locale)) {
      return saved as Locale;
    }
  } catch {
    // Modo privado estricto
  }

  const nav = navigator.language.toLowerCase();
  const matched = LOCALE_OPTIONS.find((o) => nav.startsWith(o.code));
  return matched ? matched.code : 'es';
}